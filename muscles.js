// levels: { muscle: 1..5 } colours a group by strength level, none stays neutral.
// opt.mark: { muscle: "main" | "sec" } for small figures in exercise cards (no taps, no shading).
function mmFigure(view, levels, opt) {
  levels = levels || {}; opt = opt || {};
  var mark = opt.mark, M = MM_MIRROR, regs = MM_PATHS[view];
  var s = '<svg viewBox="0 0 200 440" role="' + (mark ? 'img' : 'group') + '" aria-label="Фигура, ' + MM_NAMES_VIEW[view].toLowerCase() + '">';
  if (!mark) s += '<defs><radialGradient id="mmSh" cx=".38" cy=".3" r=".85"><stop offset="0" stop-color="#fff" stop-opacity=".26"/><stop offset=".5" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".22"/></radialGradient></defs>';
  s += '<g class="mm-body">' + FG_HEAD + '<path d="' + FG_BODY + '"/><path d="' + FG_BODY + '" transform="' + M + '"/></g>';
  FG_DECOR[view].forEach(function (d) { s += '<path class="mm-x" d="' + d + '"/><path class="mm-x" d="' + d + '" transform="' + M + '"/>'; });
  Object.keys(regs).forEach(function (k) {
    var c = mark ? (mark[k] ? " " + mark[k] : "") : (levels[k] ? " lv" + levels[k] : "");
    regs[k].forEach(function (d) {
      var a = mark ? ' class="mm-m' + c + '"' : ' class="mm-m' + c + '" data-act="muscle" data-m="' + k + '" tabindex="0" role="button" aria-label="' + MUSCLES[k][0] + '"';
      s += '<path' + a + ' d="' + d + '"/><path' + a + ' d="' + d + '" transform="' + M + '"/>';
    });
  });
  if (!mark) Object.keys(regs).forEach(function (k) {
    regs[k].forEach(function (d) { s += '<path class="mm-sh" d="' + d + '"/><path class="mm-sh" d="' + d + '" transform="' + M + '"/>'; });
  });
  return s + '</svg>';
}

// which view shows a group (first view in which it appears)
function mmViewOf(m, cur) {
  if (MM_PATHS[cur][m]) return cur;
  return MM_PATHS.front[m] ? "front" : "back";
}

function mmVideoUrl(e) {
  return "https://www.youtube.com/results?search_query=" + encodeURIComponent(e.name + " техника выполнения");
}

// small front and back figures with the muscles of one exercise: main green, secondary orange
function mmExFigure(id) {
  var e = null; EXERCISES.forEach(function (x) { if (x.id === id) e = x; });
  if (!e) return "";
  var mark = {};
  e.sec.forEach(function (m) { mark[m] = "sec"; });
  e.main.forEach(function (m) { mark[m] = "main"; });
  return '<div class="ex-figs">' + mmFigure("front", null, { mark: mark }) + mmFigure("back", null, { mark: mark }) + '</div>' +
    '<div class="ex-key"><span><i class="k-main"></i>основные мышцы</span><span><i class="k-sec"></i>помогают</span></div>';
}

function mmExercise(e, m, kind) {
  var h = '<details class="ex ' + (kind || "main") + '" data-ex="' + e.id + '"><summary><span class="ex-n">' + e.name + '</span><span class="ex-d">' + e.dose + ' · ' + e.equip + '</span></summary><div class="ex-b">';
  h += '<div class="ex-fig" data-ex="' + e.id + '"></div>';
  h += '<a class="btn ex-video" target="_blank" rel="noopener" href="' + mmVideoUrl(e) + '">▶ Смотреть видео техники</a>';
  h += '<div class="ex-h">Как делать</div><ol>' + e.steps.map(function (x) { return "<li>" + x + "</li>"; }).join("") + "</ol>";
  h += '<details class="ex-more"><summary>Частые ошибки и совет</summary><ul>' + e.mistakes.map(function (x) { return "<li>" + x + "</li>"; }).join("") + '</ul><p class="ex-tip">' + e.tip + '</p></details>';
  h += '<button class="mini" data-act="ex-note" data-ex="' + e.id + '">+ В запись тренировки</button>';
  h += "</div></details>";
  return h;
}

function mmPanel(m) {
  if (!m || !MUSCLES[m]) {
    return '<p class="note">Нажми на мышцу на фигуре или выбери группу ниже: появятся упражнения и техника.</p>';
  }
  var L = exercisesFor(m);
  var h = '<div class="row between"><h3 class="mm-title">' + MUSCLES[m][0] + '</h3><span class="chip accent num">' + (L.main.length + L.sec.length) + ' упр.</span></div>';
  h += '<p class="note">' + MUSCLES[m][1] + '</p>';
  if (L.main.length) {
    h += '<details class="exgrp main" open><summary><span>Основные</span><b class="num">' + L.main.length + '</b></summary><div class="exgrp-b">' +
      L.main.map(function (e) { return mmExercise(e, m, "main"); }).join("") + '</div></details>';
  }
  if (L.sec.length) {
    h += '<details class="exgrp sec"><summary><span>Тоже нагружают эту группу</span><b class="num">' + L.sec.length + '</b></summary><div class="exgrp-b">' +
      L.sec.map(function (e) { return mmExercise(e, m, "sec"); }).join("") + '</div></details>';
  }
  return h;
}

function mmChips(sel) {
  return MUSCLE_GROUPS.map(function (g) {
    return '<div class="mm-cg"><span class="mm-cg-n">' + g[0] + '</span><div class="mm-cg-c">' + g[1].map(function (k) {
      return '<button class="mchip" data-act="muscle" data-m="' + k + '" aria-pressed="' + (k === sel) + '">' + MUSCLES[k][0] + "</button>";
    }).join("") + '</div></div>';
  }).join("");
}
